#!/usr/bin/env python3
"""Regenerate e2e/client/smoke_methods.go from docs/api-coverage.csv.

Run from the repository root:

    python3 e2e/client/gen_smoke.py

Then go test ./e2e/client/ -run TestSmokeRequestsEncode
"""

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "proto/schema/telegram_api_layer232.tl"
CSV = ROOT / "docs/api-coverage.csv"
OUT = Path(__file__).resolve().parent / "smoke_methods.go"

# Implemented, but not in telegram_api_layer232.tl. Constructors are the ones
# the server registers.
EXTRA = {
    "channels.editCreator": -1892102881,
    "channels.getFutureCreatorAfterLeave": -1610016593,
    "messages.getStatsURL": -2127811866,
}


def constructors():
    found = {}
    for line in SCHEMA.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("//") or line.startswith("---"):
            continue
        m = re.match(r"([a-zA-Z0-9_.]+)#([0-9a-fA-F]+)\s*(.*?)\s*=\s*[^;]+;", line)
        if not m:
            continue
        crc = int(m.group(2), 16)
        if crc >= 2**31:
            crc -= 2**32
        found[m.group(1)] = crc
    found.update(EXTRA)
    return found


def main():
    crc = constructors()
    rows = list(csv.DictReader(CSV.open()))
    want = [
        r["method"]
        for r in rows
        if r["status"] == "implemented" and r["phase"] in ("P0", "P1")
    ]
    missing = [name for name in want if name not in crc]
    if missing:
        raise SystemExit("no constructor for: " + ", ".join(missing))
    lines = [
        "// Code generated by e2e/client/gen_smoke.py. DO NOT EDIT.",
        "package e2e",
        "",
        "// smokeMethods is every implemented P0/P1 method in docs/api-coverage.csv.",
        "var smokeMethods = []smokeMethod{",
    ]
    for name in want:
        lines.append(f'\t{{Name: "{name}", CRC: {crc[name]}}},')
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(want)} methods to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
